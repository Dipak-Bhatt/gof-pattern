using IteratorDesignPattern.Aggregate;
using IteratorDesignPattern.Infrastructure;
using IteratorDesignPattern.Models;

Console.WriteLine("=== Iterator Design Pattern — Tenant Run ===\n");
Console.WriteLine("AGGREGATE  TenantRun            owns the ordered tenants; its array stays private");
Console.WriteLine("ITERATOR   IIterator<Tenant>    HasNext / Next / Reset");
Console.WriteLine("CONCRETE   TenantRunIterator    stops on the time budget or cancellation");
Console.WriteLine("IDIOM      TenantRun.Startable  the same walk with yield return\n");

var run = new TenantRun(new[]
{
    MakeTenant(1, "Acme Foods"),
    MakeTenant(2, "Northwind Bank"),
    MakeTenant(3, "Contoso Textiles"),
    MakeTenant(4, "Fabrikam Logistics"),
    MakeTenant(5, "Tailspin Hotels"),
});

const long slot = 2;
var budget = TimeSpan.FromMinutes(15);
var work = TimeSpan.FromMinutes(7);

Console.WriteLine($"--- A run in slot {slot} rotates the sorted tenants ---");
Console.WriteLine("  " + string.Join(" -> ", run.Order(slot).Select(tenant => tenant.Name)) + "\n");

Console.WriteLine("--- Forward traversal (HasNext / Next), 15-minute budget, 7 minutes per tenant ---");
var clock = new VirtualTimeProvider();
var startedAt = clock.GetTimestamp();
var iterator = run.CreateIterator(slot, clock, startedAt, budget, CancellationToken.None);
var started = new List<Tenant>();

while (iterator.HasNext)
{
    var tenant = iterator.Next();
    started.Add(tenant);
    Console.WriteLine($"  started {tenant.Name,-20} at +{clock.GetElapsedTime(startedAt).TotalMinutes,2:N0} min");
    clock.Advance(work);
}

var remaining = run.Order(slot).Skip(started.Count).Select(tenant => tenant.Name).ToList();
Console.WriteLine($"  stopped after {started.Count} tenants: +{clock.GetElapsedTime(startedAt).TotalMinutes:N0} min >= 15");
Console.WriteLine($"  not started: {(remaining.Count == 0 ? "none" : string.Join(", ", remaining))}\n");

Console.WriteLine("--- The C# idiom: foreach over yield return ---");
var clock2 = new VirtualTimeProvider();
var startedAt2 = clock2.GetTimestamp();

foreach (var tenant in run.Startable(slot, clock2, startedAt2, budget, CancellationToken.None))
{
    Console.WriteLine($"  started {tenant.Name,-20} at +{clock2.GetElapsedTime(startedAt2).TotalMinutes,2:N0} min");
    clock2.Advance(work);
}

Console.WriteLine("\n--- Two cursors over one aggregate keep separate positions ---");
var clock3 = new VirtualTimeProvider();
var startedAt3 = clock3.GetTimestamp();
var first = run.CreateIterator(slot, clock3, startedAt3, TimeSpan.FromHours(1), CancellationToken.None);
var second = run.CreateIterator(slot, clock3, startedAt3, TimeSpan.FromHours(1), CancellationToken.None);
Console.WriteLine($"  cursor A: {first.Next().Name}");
Console.WriteLine($"  cursor B: {second.Next().Name}");
Console.WriteLine($"  cursor A: {first.Next().Name}   (B is still on its first)\n");

Console.WriteLine("--- Reset returns a cursor to the start ---");
var resettable = run.CreateIterator(slot, clock3, startedAt3, TimeSpan.FromHours(1), CancellationToken.None);
resettable.Next();
resettable.Next();
Console.WriteLine($"  after two steps: {resettable.Next().Name}");
resettable.Reset();
Console.WriteLine($"  after Reset:     {resettable.Next().Name}\n");

Console.WriteLine("--- Cancellation stops the walk before the next tenant ---");
var clock4 = new VirtualTimeProvider();
var startedAt4 = clock4.GetTimestamp();
using var stop = new CancellationTokenSource();
var cancelled = run.CreateIterator(slot, clock4, startedAt4, TimeSpan.FromHours(1), stop.Token);
var count = 0;

while (cancelled.HasNext)
{
    Console.WriteLine($"  started {cancelled.Next().Name}");
    count++;
    clock4.Advance(work);

    if (count == 2)
        stop.Cancel();
}

Console.WriteLine($"  cancelled after {count} of {run.Count} tenants\n");

Console.WriteLine("=== Key Insight ===");
Console.WriteLine("The client never sees TenantRun's private array or its rotation index. It asks the");
Console.WriteLine("aggregate for a cursor and pulls one tenant at a time. The iterator's stop rules");
Console.WriteLine("(time budget, cancellation) travel with the cursor, so the same aggregate can be");
Console.WriteLine("walked by several callers at once. In C#, foreach over yield return is this pattern");
Console.WriteLine("with the iterator class generated by the compiler; the explicit class here shows the");
Console.WriteLine("roles the language normally hides.");

static Tenant MakeTenant(int number, string name) =>
    new(Guid.Parse($"00000000-0000-0000-0000-{number:D12}"), name);
